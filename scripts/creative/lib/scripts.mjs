/**
 * True when `text` contains at least one character written in `script`.
 * Latin-writing scripts always pass.
 */
export function hasScriptText(script, text) {
  const probe = SCRIPT_PROBE[script];
  if (!probe) return true;
  return new RegExp(`[${probe}]`, 'u').test(text ?? '');
}

export function fontFor(asc) {
  const script = scriptFor(asc);
  const font = SCRIPT_FONTS[script];
  if (!font) throw new Error(`No font stack for script "${script}" (locale ${asc})`);
  return { script, headroom: HEADROOM[script] ?? '0.10em', ...font };
}

/** Every distinct script the locale table needs. */
export function allScripts() {
  return [...new Set(Object.values(LOCALE_SCRIPT))];
}
