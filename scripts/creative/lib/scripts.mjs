/**
 * Script classification and the per-script font stack.
 *
 * The type system is the one part of a localized screenshot that cannot be
 * faked: a frame set in a font that lacks the script renders tofu boxes, and a
 * frame with a 1.0 line box under Devanagari or Thai clips its own ascenders.
 *
 * Basteleur (the app's display face) covers Latin, Latin Extended, Greek — and
 * nothing else. So:
 *   - Latin / Greek locales use Basteleur, the app's own voice.
 *   - Every other script gets the matching Noto Serif, at the same optical size,
 *     with a script-specific line-height and, where the script needs it, a
 *     larger size to hold the same visual weight.
 *
 * Font files are small committed subsets (`store/creative/fonts/*.woff2`)
 * generated by `scripts/creative/fonts.mjs` from Google Fonts' `text=`
 * subsetting API, so a render is offline and deterministic.
 */

