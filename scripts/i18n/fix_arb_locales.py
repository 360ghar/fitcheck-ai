#!/usr/bin/env python3
"""Force every app_*.arb `@@locale` to match its filename.

`flutter gen-l10n` rejects a catalog whose `@@locale` disagrees with the file
name and then silently generates only the English class. Older runs of
`translate_arb.py` copied the template's `@@locale: en` into every file, so this
repairs a tree that was generated by one of those runs.
"""
import json
import sys
from pathlib import Path

L10N = Path(__file__).resolve().parents[2] / "flutter" / "lib" / "l10n"
changed = 0
for path in sorted(L10N.glob("app_*.arb")):
    code = path.stem[len("app_") :]
    data = json.loads(path.read_text(encoding="utf-8"))
    if data.get("@@locale") != code:
        data["@@locale"] = code
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"fixed {path.name}: @@locale -> {code}")
        changed += 1
print(f"{changed} file(s) repaired")
sys.exit(0)
